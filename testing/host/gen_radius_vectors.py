"""Known-answer vectors for the RADIUS host tests (radius_test.cpp): an independent reference of RFC 2865 (User-Password,
Response Authenticator) and RFC 3579 3.2 (Message-Authenticator) with the Python standard library only.

    python -I testing/host/gen_radius_vectors.py > testing/host/radius_vectors.h

Run it only to change the vectors; the output is committed.
"""
import hashlib
import hmac
import struct

SECRET = b"s3cr3t-of-the-test"
RA = bytes.fromhex("0102030405060708090a0b0c0d0e0f10")


def attr(t, v):
    return bytes([t, 2 + len(v)]) + v


def hide(password, secret, ra):
    p = password + b"\0" * ((16 - len(password) % 16) % 16) if password else b"\0" * 16
    out, prev = b"", ra
    for i in range(0, len(p), 16):
        b = hashlib.md5(secret + prev).digest()
        c = bytes(x ^ y for x, y in zip(p[i:i + 16], b))
        out += c
        prev = c
    return out


def request(identifier, user, password, secret, ra, nas_id=b"", nas_ip=None, nas_port=None, port_type=None,
            service=None, port_id=b"", calling=b""):
    attrs = attr(80, b"\0" * 16) + attr(1, user) + attr(2, hide(password, secret, ra))
    if nas_id:
        attrs += attr(32, nas_id)
    if nas_ip:
        attrs += attr(4, bytes(nas_ip))
    if nas_port is not None:
        attrs += attr(5, struct.pack(">I", nas_port))
    if port_type is not None:
        attrs += attr(61, struct.pack(">I", port_type))
    if service is not None:
        attrs += attr(6, struct.pack(">I", service))
    if port_id:
        attrs += attr(87, port_id)
    if calling:
        attrs += attr(31, calling)
    pkt = bytes([1, identifier]) + struct.pack(">H", 20 + len(attrs)) + ra + attrs
    mac = hmac.new(secret, pkt, hashlib.md5).digest()
    return pkt[:22] + mac + pkt[38:]


def answer(code, identifier, ra, secret, attrs, with_ma=True, break_ma=False, break_auth=False):
    if with_ma:
        attrs = attr(80, b"\0" * 16) + attrs
    length = 20 + len(attrs)
    if with_ma:
        tmp = bytes([code, identifier]) + struct.pack(">H", length) + ra + attrs
        mac = hmac.new(secret, tmp, hashlib.md5).digest()
        if break_ma:
            mac = bytes([mac[0] ^ 1]) + mac[1:]
        attrs = attrs[:2] + mac + attrs[18:]
    auth = hashlib.md5(bytes([code, identifier]) + struct.pack(">H", length) + ra + attrs + secret).digest()
    if break_auth:
        auth = bytes([auth[0] ^ 0x80]) + auth[1:]
    return bytes([code, identifier]) + struct.pack(">H", length) + auth + attrs


def cisco(avpair):
    return attr(26, struct.pack(">I", 9) + attr(1, avpair))


def c_array(name, data):
    lines = [f"inline const uint8_t {name}[] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    out = ["// Generated by gen_radius_vectors.py (Python standard library: hashlib, hmac). Do not edit.",
           "#pragma once", "", "#include <cstdint>", "",
           f'inline const char RV_SECRET[] = "{SECRET.decode()}";',
           c_array("RV_RA", RA)]
    out.append(c_array("RV_REQUEST", request(7, b"jdoe", b"correct horse", SECRET, RA, b"consoleserver",
                                             (192, 168, 8, 104), 1, 5, 1, b"ssh1", b"192.168.8.100")))
    # a password of 40 bytes: three blocks
    out.append(c_array("RV_REQUEST_LONG", request(200, b"admin@example.com", b"x" * 40, SECRET, RA)))
    ok_attrs = attr(6, struct.pack(">I", 6)) + cisco(b"shell:priv-lvl=15") + attr(25, b"CS-ADMIN")
    out.append(c_array("RV_ACCEPT_15", answer(2, 7, RA, SECRET, ok_attrs)))
    out.append(c_array("RV_ACCEPT_1", answer(2, 7, RA, SECRET, attr(6, struct.pack(">I", 7)) + cisco(b"shell:priv-lvl=1"))))
    out.append(c_array("RV_ACCEPT_ADMIN_ONLY", answer(2, 7, RA, SECRET, attr(6, struct.pack(">I", 6)))))
    out.append(c_array("RV_ACCEPT_PROMPT_ONLY", answer(2, 7, RA, SECRET, attr(6, struct.pack(">I", 7)))))
    out.append(c_array("RV_REJECT", answer(3, 7, RA, SECRET, attr(18, b"Authentication failed"))))
    out.append(c_array("RV_ACCEPT_NO_MA", answer(2, 7, RA, SECRET, ok_attrs, with_ma=False)))
    out.append(c_array("RV_ACCEPT_BAD_MA", answer(2, 7, RA, SECRET, ok_attrs, break_ma=True)))
    out.append(c_array("RV_ACCEPT_BAD_AUTH", answer(2, 7, RA, SECRET, ok_attrs, break_auth=True)))
    out.append(c_array("RV_ACCEPT_WRONG_SECRET", answer(2, 7, RA, b"another secret", ok_attrs)))
    print("\n\n".join(out))


if __name__ == "__main__":
    main()
